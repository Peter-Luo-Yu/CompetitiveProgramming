int main () {
    ios_base::sync_with_stdio(false);
    cin.tie(nullptr);

    //freopen("input.txt", "r", stdin);
    //freopen("output.txt", "w", stdout);

    int n; cin >> n;

    ll MOD = 1e9 + 7;
    // dp[i] = number of possibilities to get sum of (i + 1)
    vector<ll> dp (n);

    for (int i = 0; i < 6; i++) {
        dp[i] = 1;
    }

    for (int i = 0; i < n; i++) {
        for (int j = 1; j <= 6; j++) {
            if (i - j >= 0) {
                dp[i] = (dp[i] + dp[i - j]) % MOD;
            }
        }
    }

    //print(dp);
    
    cout << dp[n - 1] << endl;
    


    return 0;
}
